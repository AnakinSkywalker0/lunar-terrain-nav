"""Write docs/GUIDANCE_ABLATION_TABLES.md (markdown tables from the analysis CSVs) and copy figures to docs/figures.

All numbers come from the files under out/guidance_ablation/analysis_*; nothing is typed by hand.
"""
import json
import shutil
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
A = ROOT / "out/guidance_ablation"
DOCS = ROOT / "docs"


def md(df, floatfmt="{:.2f}"):
    cols = list(df.columns)
    lines = ["| " + " | ".join(cols) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    for _, row in df.iterrows():
        cells = []
        for c in cols:
            v = row[c]
            cells.append(floatfmt.format(v) if isinstance(v, float) else str(v))
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines)


def main():
    out = ["# Guidance ablation: result tables (generated)", "",
           "Generated by `tools/make_results_tables.py` from `out/guidance_ablation/analysis_*`. Do not edit by hand.",
           "Rates are means over terrain areas (the independent unit). `map miss` is the contact point in the map frame."]

    t = pd.read_csv(A / "_existing_runs/frame_artifact_by_condition.csv")
    t = t[["condition", "arm", "areas", "abs10", "map10", "abs50", "map50"]]
    t.columns = ["condition", "arm", "areas", "success@10m true frame", "success@10m map frame",
                 "success@50m true frame", "success@50m map frame"]
    out += ["", "## T1. Same landings, two scoring frames (existing runs: 3 transfer areas + 1 Site04 area)", md(t)]

    t = pd.read_csv(A / "analysis_12areas/table_by_condition_guidance_arm.csv")
    sub = t[t.condition == "relief_positive"][["guidance", "arm", "violation", "map_miss", "map_ok_10", "map_ok_50"]]
    out += ["", "## T2. Changed terrain (16 m bump): guidance x correction rule, 12 areas", md(sub)]

    sub = t[t.condition.isin(["aligned", "tie3", "tie8", "map_shift"]) & (t.guidance == "baseline")][
        ["condition", "arm", "violation", "map_miss", "map_ok_10", "abs_ok_10"]]
    sub.columns = ["condition", "arm", "violation", "map miss (m)", "success@10m map frame", "success@10m true frame"]
    out += ["", "## T3. Map-offset conditions, baseline guidance, 12 areas", md(sub)]

    g2 = pd.read_csv(A / "analysis_12areas/g2_authority_vs_geometric.csv")
    g2 = g2[g2.metric == "violation"][["condition", "mean_a", "mean_b", "areas_a_lower", "areas_a_higher", "sign_test_p"]]
    g2.columns = ["condition", "authority gate", "geometric", "areas lower", "areas higher", "sign-test p"]
    out += ["", "## T4. Authority-aware gate vs geometric, violation rate (pre-registered G2)", md(g2, "{:.3f}")]

    summ = json.loads((A / "analysis_12areas/summary.json").read_text())
    out += ["", "## T5. Pre-registered verdict strings (generated by the analysis script)", "```",
            json.dumps(summ["g1"], indent=1), "g2_supported: " + str(summ["g2_supported"]), "```"]

    g3 = pd.read_csv(A / "g3_20261108/g3_table.csv")[["condition", "arm", "violation", "map_miss", "ok10", "ok50"]]
    g3.columns = ["condition", "arm", "violation", "map miss (m)", "success@10m", "success@50m"]
    out += ["", "## T6. Classical Kalman + chi-square gate (G3), baseline guidance, 12 areas", md(g3)]

    sw = pd.read_csv(A / "analysis_sweep/sweep_by_amplitude_arm.csv")
    for metric, title in (("ok10", "success (miss < 10 m map frame, vz < 2, vh < 1)"), ("miss", "mean map-frame miss (m)"),
                          ("violation", "speed-violation rate")):
        piv = sw.pivot(index="amp", columns="arm", values=metric).reset_index()
        piv = piv[["amp", "off", "geometric", "bounded", "authority", "utility", "kf_chi2"]]
        piv["amp"] = piv["amp"].map(lambda a: "0 (aligned)" if a == 0 else f"{a:g} m")
        out += ["", f"## T7. Unmodelled-relief sweep: {title}, 12 areas", md(piv)]
    kv = pd.read_csv(A / "analysis_sweep/sweep_kf_vs_others.csv")
    kv = kv[(kv.metric == "miss") & kv.vs.isin(["geometric", "utility"])][
        ["amp", "vs", "kf_mean", "other_mean", "areas_kf_lower", "areas_kf_higher", "sign_p", "boot_lo", "boot_hi"]]
    kv.columns = ["amp (m)", "vs", "kf miss", "other miss", "areas kf lower", "areas kf higher", "sign p", "boot95 lo", "boot95 hi"]
    out += ["", "## T8. Kalman+chi2 minus other arm, mean miss (m), paired over 12 areas", md(kv, "{:.3f}")]
    out += ["", "## T9. Break-even amplitudes (first sweep amplitude at which the arm is no better than doing nothing / violation > 5%)",
            "```", (A / "analysis_sweep/sweep_breakeven.json").read_text(), "```"]

    im = pd.read_csv(A / "analysis_imu/imu_by_condition_bias_arm.csv")
    im["bias"] = im["bias"].map(lambda b: f"{b:g}")
    im = im[["condition", "bias", "arm", "miss", "violation", "ok10"]]
    im = im.drop_duplicates(subset=["condition", "bias", "arm"], keep="last")
    im.columns = ["condition", "accel bias (m/s^2)", "arm", "map miss (m)", "violation", "success@10m"]
    out += ["", "## T10. Accelerometer-bias stress (constants not retuned), 12 areas", md(im)]

    (DOCS / "GUIDANCE_ABLATION_TABLES.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    fig = DOCS / "figures"; fig.mkdir(exist_ok=True)
    for src, name in [(A / "analysis_12areas/fig_violations.png", "violations_by_guidance_arm.png"),
                      (A / "analysis_12areas/fig_success_map10.png", "success_map10_by_guidance_arm.png"),
                      (A / "analysis_sweep/fig_relief_sweep.png", "relief_sweep.png"),
                      (A / "analysis_imu/fig_imu_stress.png", "imu_stress.png"),
                      (A / "_existing_runs/fig_frame_artifact.png", "frame_artifact.png")]:
        shutil.copy(src, fig / name)
    print("wrote docs/GUIDANCE_ABLATION_TABLES.md and docs/figures/*")


if __name__ == "__main__":
    main()
